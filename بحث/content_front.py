def introduction(doc):
    h2(doc, "مقدمة البحث")
    h4(doc, "أولًا: أهمية الموضوع")
    body(doc, "لا تستقيم دراسةُ التاريخ العربي الإسلامي دون إحكام النظر في العصر الجاهلي؛ إذ كان هذا العصرُ البوتقةَ التي تشكَّلت فيها "
              "القيمُ الاجتماعية والأخلاقية التي تعامل معها الوحيُ بعد ذلك تعاملَ المُقِرِّ أو المُهذِّب أو المُبطِل. وقد قسَّم العلماء موقف "
              "الإسلام مما ورثه عن الجاهلية إلى ثلاثة مسالك: إقرارٌ لما وافق الشرع كالكريم والضيافة والوفاء بالعهد، وتهذيبٌ لما شابَه "
              "نقصٌ كالعصبية القبلية والثأر، وإبطالٌ لما خالف التوحيد والفطرة كعبادة الأصنام والاستقسام بالأزلام ووأد البنات. ومن هنا "
              "كان ضبطُ «العادات الجاهلية» ضبطًا موثقًا ضرورةً علميةً لدارس التاريخ والأدب والشريعة واللغة جميعًا.")
    body(doc, "وتزداد أهمية الموضوع بما يكتنفه من مخاطرَ منهجية؛ فأخبارُ الجاهلية وصلت إلينا بأسانيدَ متأخرة، واختلط فيها الصحيحُ "
              "بالمُرسل والموضوع، وامتزج الشعرُ الجاهلي بالمنحول والمولَّد، ودخلت في بعض المصنفات عاداتٌ إسلامية ظنَّها بعضُ الكُتّاب "
              "جاهلية. فكان من الواجب على من يتصدى لهذا الباب أن يُحكِم التوثيق، ويُفرِّق بين مراتب النصوص، ولا ينسب إلى الجاهلية إلا "
              "ما شهد له مصدرٌ يُعتدُّ به.")
    h4(doc, "ثانيًا: إشكالية البحث وأسئلته")
    body(doc, "يدور هذا البحث حول إشكالية مركزية: كيف نُعيد بناءَ صورة العادات الاجتماعية والدينية والأخلاقية عند العرب قبل الإسلام "
              "بناءً موثقًا من مصادره الأصلية، مع التمييز بين الرواية التاريخية والنص الأدبي، وضبط كل شاهدٍ ضبطًا يُتيح للباحث الرجوعَ "
              "إليه مباشرة؟ وتتفرع عن هذه الإشكالية أسئلةٌ فرعية: ما الشواهد التاريخية والأدبية الدالة على كل عادة من العادات الإحدى "
              "والعشرين المحددة؟ وما درجة دلالة كل نص على ما نُسب إليه؟ وكيف نميز العادة الجاهلية الأصيلة مما دخل عليها من عادات "
              "إسلامية لاحقة؟")
    h4(doc, "ثالثًا: منهج البحث")
    body(doc, "سلكت هذه الدراسة المنهجَ الاستقرائيَّ التوثيقيَّ التحليلي، على القواعد الآتية:")
    bullet(doc, "الاعتماد على المصادر التراثية الأصلية أولًا: كتب السِّيَر (ابن إسحاق، ابن هشام)، والتاريخ (الطبري، ابن كثير)، "
                "والأنساب والأخبار (ابن حبيب، الأصفهاني)، والأدب (الجاحظ، ابن قتيبة، ابن عبد ربه، الميداني)، والشعر (شروح المعلقات، "
                "الدواوين، المفضليات، الحماسة)، والمعاجم، والتفاسير.")
    bullet(doc, "جمعُ شاهدين أو أكثر لكل عادة، مع تنويع أنواعها (تاريخ، أدب، شعر، مثل، تفسير) ليَشُدَّ بعضُها بعضًا.")
    bullet(doc, "نقلُ النص حرفيًّا من مصدره، وعزوُه إلى (المؤلف، الكتاب، الطبعة أو التحقيق، الجزء، الصفحة) بحسب الطبعات المعتمدة في "
                "المكتبة الشاملة، مع التنبيه إلى اختلاف الصفحات باختلاف الطبعات.")
    bullet(doc, "إفرادُ فقرة «وجه الاستشهاد» لبيان دلالة النص على العادة، ودرجة تلك الدلالة، وما قد يَرِد على النص من ملاحظة نقدية "
                "(إرسال، انقطاع، نَحْل، اختلاف رواية).")
    bullet(doc, "التأكد من كون الشاهد متصلًا بالعرب قبل الإسلام: بأن يكون قائلُه أو بطلُه جاهليًّا، أو يصف ممارسةً جاهلية صريحة، "
                "وتجنُّب الاستشهاد بعادات إسلامية لاحقة.")
    bullet(doc, "الاستعانة بالدراسات الحديثة الموثقة (وفي مقدمتها «المفصل في تاريخ العرب قبل الإسلام» للدكتور جواد علي) عند الحاجة "
                "إلى الجمع والتحليل فقط، من غير إغناءٍ بها عن الأصول.")
    bullet(doc, "تزويدُ كل شاهد بـ«عبارة بحث» حرفية تعمل داخل المكتبة الشاملة، فيكون الوصول إلى النص مضمونًا ولو تغيَّرت الطبعات "
                "والصفحات.")
    h4(doc, "رابعًا: نظام التوثيق في البحث")
    body(doc, "أرقام الصفحات الواردة في هذا البحث مأخوذة من نسخ المكتبة الشاملة المُرقَّمة «موافق للمطبوع» للطبعات المثبتة عند كل شاهد؛ "
              "فإذا ذُكر مثلًا: «ابن كثير، البداية والنهاية، ط دار ابن كثير، ج٢ ص٤٩٩» فالمراد الصفحة ٤٩٩ من الجزء الثاني في تلك الطبعة، "
              "وهي تقابل في طبعة دار هجر (تحقيق التركي) موضعًا آخر من الجزء الثالث. ولهذا ثُبِّت مع كل شاهد «عبارة البحث» وهي العمدة عند "
              "الاختلاف. وما لم يُضبط رقمُ صفحته من الشواهد صُرِّح بذلك وعُوِّض برقم الباب أو الفصل أو القصيدة أو الحديث، التزامًا بالأمانة "
              "العلمية ورفضًا لتوليد الأرقام.")
    h4(doc, "خامسًا: هيكل البحث")
    body(doc, "انتظم البحث في مقدمة، وثلاثة أقسام، وخاتمة، وثلاثة ملاحق:")
    bullet(doc, "القسم الأول: العادات الاجتماعية (الكرم والضيافة، الفداء وحماية الجار، الوفادة والوساطة، العصبية القبلية، الأخذ بالثأر، "
                "اللباس والزينة، الاحتفال بالمناسبات).")
    bullet(doc, "القسم الثاني: العادات الدينية (تعظيم البيت الحرام، عبادة الأصنام، التحنث، الوفاء بالنذر، الطهارة والاغتسال، الاستقسام "
                "بالأزلام، الكهانة والعرافة).")
    bullet(doc, "القسم الثالث: العادات الأخلاقية (الوفاء بالعهد، الشجاعة والفروسية، الصبر والجلد، الحلم، شرب الخمر، لعب الميسر، وأد البنات).")
    bullet(doc, "ثم خاتمة بأهم النتائج، فملحق (أ): جدول عبارات البحث في المكتبة الشاملة لجميع الشواهد، وملحق (ب): فهرس الشواهد "
                "الشعرية، وملحق (ج): معجم مصطلحات العادات الجاهلية، فقائمة المصادر والمراجع.")
    page_break(doc)



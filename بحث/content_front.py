           ["[أ]", "خبر أدبي من كتب الأدب والأخبار", "دلالة قوية على شيوع العادة في الوعي الجمعي؛ مع الانتباه لتوسع الأدباء"],
           ["[ش]", "شعر جاهلي أو مخضرم", "سجلُّ العرب؛ دلالته على القيم والأخلاق قوية، وفي التفاصيل الخبرية يُضمّ للرواية"],

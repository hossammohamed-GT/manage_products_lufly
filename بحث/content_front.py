HERE = os.path.dirname(os.path.abspath(__file__))
ORN = os.path.join(HERE, "assets", "cover_ornament.png")

TITLE = "العادات الاجتماعية والدينية والأخلاقية عند العرب قبل الإسلام"
SUBTITLE = ("دراسةٌ توثيقيةٌ بالشواهد التاريخية والأدبية، مع ضبط المصادر والمؤلِّفين والأجزاء والصفحات، "
            "وعبارات البحث الموصِّلة إلى كل شاهد داخل المكتبة الشاملة")


def cover(doc):
    p = add_par(doc)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    spacing(p, before=0, after=2)
    if os.path.exists(ORN):
        p.add_run().add_picture(ORN, width=Cm(16.4))

    p = add_par(doc); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    spacing(p, before=10, after=2)
    txt(p, "بسم الله الرحمن الرحيم", size=18, bold=True, color=GOLD, name=AR_FONT_QUOTE)

    p = add_par(doc); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    spacing(p, before=18, after=4)
    txt(p, "بحثٌ علميٌّ موثَّق", size=14, color=GRAY)

    p = add_par(doc); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    shade_par(p, HEX_PANEL)
    par_borders(p, sides=("top", "bottom"), color=HEX_GOLD, sz="12", space="8")
    spacing(p, before=10, after=10, line=1.5)
    txt(p, TITLE, size=25, bold=True, color=GREEN)

    p = add_par(doc); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    spacing(p, before=4, after=12, line=1.4)
    txt(p, SUBTITLE, size=13.5, color=DARK)

    p = add_par(doc); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    shade_par(p, HEX_CREAM)
    par_borders(p, sides=("right", "left"), color=HEX_GOLD, sz="8", space="8")
    spacing(p, before=6, after=6, line=1.6)
    txt(p, "إحدى وعشرون عادةً في ثلاثة أقسام: اجتماعية، ودينية، وأخلاقية\n", size=13, bold=True, color=GREEN)
    txt(p, "أكثر من ستين شاهدًا من الروايات التاريخية والنصوص الأدبية والشعرية والأمثال\n", size=12.5)
    txt(p, "من كتب: السِّير، والتاريخ، والأنساب، والأدب، والأخبار، والأمثال، والمعاجم، والتفاسير، والدواوين", size=12.5)

    p = add_par(doc); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    spacing(p, before=20, after=0)
    txt(p, "جمادى الأولى ١٤٤٨هـ  —  أكتوبر ٢٠٢٦م", size=12.5, color=GRAY)

    p = add_par(doc); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    spacing(p, before=8, after=0)
    if os.path.exists(ORN):
        p.add_run().add_picture(ORN, width=Cm(16.4))
    page_break(doc)



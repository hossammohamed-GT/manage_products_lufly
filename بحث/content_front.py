    bullet(doc, "شاهدان أو أكثر لكل عادة، مُصنَّفةً بين رواية تاريخية، وخبر أدبي، وشعر، ومَثَل، ونص شرعي وتفسيري.", lead="٢) الشواهد: ")
    bullet(doc, "نقل النص الأصلي كما ورد في مصدره، داخل إطار مميز، مع عزوٍ دقيق (المؤلف، الكتاب، الطبعة/التحقيق، الجزء، الصفحة).", lead="٣) النص والعزو: ")

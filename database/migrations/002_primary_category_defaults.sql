INSERT IGNORE INTO product_categories (product_id, category_id)
SELECT p.id, c.id
FROM tmp_lufly_primary_category_defaults AS defaults_map
JOIN products AS p ON p.id = defaults_map.product_id
JOIN categories AS c ON c.category_key = defaults_map.category_key AND c.parent_id IS NULL;

-- Report matching products by root category for a quick import check.
SELECT defaults_map.category_key, COUNT(p.id) AS matching_products
FROM tmp_lufly_primary_category_defaults AS defaults_map
LEFT JOIN products AS p ON p.id = defaults_map.product_id
GROUP BY defaults_map.category_key
ORDER BY defaults_map.category_key;

